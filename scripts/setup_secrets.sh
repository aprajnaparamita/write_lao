#!/usr/bin/env bash
# ── scripts/setup_secrets.sh ─────────────────────────────────────────────────
# Reads the project-root .env and regenerates lib/config/secrets.dart.
# Run this once after cloning, or whenever the .env changes.
#
# Usage:
#   bash scripts/setup_secrets.sh
# ─────────────────────────────────────────────────────────────────────────────

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
ENV_FILE="$ROOT_DIR/.env"
OUT_FILE="$ROOT_DIR/lib/config/secrets.dart"

if [[ ! -f "$ENV_FILE" ]]; then
  echo "❌  .env not found at $ENV_FILE"
  echo "   Copy .env.example to .env and fill in your values."
  exit 1
fi

# Load the .env (ignore blank lines and comments)
SENTRY_DSN=""

while IFS='=' read -r key value; do
  [[ -z "$key" || "$key" == \#* ]] && continue
  key="${key// /}"   # trim spaces
  value="${value// /}"
  case "$key" in
    SENTRY_DSN) SENTRY_DSN="$value" ;;
  esac
done < "$ENV_FILE"

cat > "$OUT_FILE" << EOF
// ── App secrets ─────────────────────────────────────────────────────────────
// AUTO-GENERATED by scripts/setup_secrets.sh — DO NOT COMMIT.
// Re-generate: bash scripts/setup_secrets.sh

// ignore_for_file: constant_identifier_names

/// Sentry DSN for error reporting. Set to empty string to disable Sentry.
const String SENTRY_DSN = '$SENTRY_DSN';
EOF

echo "✅  lib/config/secrets.dart written."
